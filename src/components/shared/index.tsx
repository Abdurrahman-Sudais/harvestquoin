export function GradeBadge({ grade, size = "md", predicted = false, className }: { grade: GradeCode; size?: "sm" | "md" | "lg"; predicted?: boolean; className?: string }) {
  const sz = size === "sm" ? "h-5 min-w-5 text-[11px]" : size === "lg" ? "h-10 min-w-10 text-lg" : "h-7 min-w-7 text-sm";
  return (
    <span
      className={cn(
        "inline-flex items-center justify-center rounded-md px-1.5 font-display font-bold",
        sz,
        predicted ? "border-2 border-dashed bg-transparent " + (grade === "A" ? "border-forest-600 text-forest-700" : grade === "B" ? "border-lime-500 text-forest-800" : grade === "C" ? "border-amber-500 text-amber-700" : "border-red-500 text-red-600") : GRADE_STYLE[grade],
        className
      )}
      title={predicted ? `Predicted grade ${grade} (simulated)` : `Inspection grade ${grade}`}
    >
      {grade === "R" ? "Rej" : grade}
    </span>
  );
}

