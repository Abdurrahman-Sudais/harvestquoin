export function ScoreBar({ score, min, className, urgency = false }: { score: number; min?: number; className?: string; urgency?: boolean }) {
  const color = urgency
    ? score >= 62 ? "bg-red-500" : score >= 46 ? "bg-amber-500" : score >= 30 ? "bg-sky-500" : "bg-emerald-500"
    : score >= 80 ? "bg-forest-600" : score >= 65 ? "bg-lime-500" : score >= 50 ? "bg-amber-500" : "bg-red-500";
  return (
    <div className={cn("relative h-2 w-full rounded-full bg-muted", className)}>
      <div className={cn("h-2 rounded-full", color)} style={{ width: `${Math.max(2, Math.min(100, score))}%` }} />
      {min !== undefined && <div className="absolute -top-1 h-4 w-0.5 bg-forest-950/70" style={{ left: `${min}%` }} title={`Limit ${min}`} />}
    </div>
  );
}
