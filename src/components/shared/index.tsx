/** Produce photography with a graceful illustrated fallback if the image fails to load. */
export function ProducePhoto({ name, alt, className }: { name: keyof typeof PHOTOS | string; alt: string; className?: string }) {
  const [failed, setFailed] = useState(false);
  const src = PHOTOS[name];
  if (failed || !src)
    return (
      <div className={cn("relative overflow-hidden bg-gradient-to-br from-forest-700 via-forest-600 to-lime-500", className)} role="img" aria-label={alt}>
        <div className="absolute inset-0 bg-grain opacity-40" />
        <svg viewBox="0 0 200 120" className="absolute inset-0 h-full w-full opacity-90" preserveAspectRatio="xMidYMid slice" aria-hidden>
          {[...Array(9)].map((_, i) => (
            <g key={i} transform={`translate(${20 + (i % 3) * 60 + (Math.floor(i / 3) % 2) * 25}, ${25 + Math.floor(i / 3) * 35})`}>
              <circle r="16" fill={["#dc2626", "#ef4444", "#f97316"][i % 3]} />
              <path d="M-6 -14 Q0 -20 6 -14 M0 -16 L0 -21" stroke="#65a30d" strokeWidth="3" fill="none" strokeLinecap="round" />
              <ellipse cx="-5" cy="-5" rx="4" ry="2.5" fill="white" opacity="0.35" />
            </g>
          ))}
        </svg>
      </div>
    );
  return <img src={src} alt={alt} loading="lazy" onError={() => setFailed(true)} className={cn("object-cover", className)} />;
}

